-- ============================================================
-- GeoPulse - Day 5: Snowflake Geospatial Warehouse Setup
-- All datasets used in this project are synthetic and anonymized.
-- ============================================================

-- 1. Create warehouse
CREATE WAREHOUSE IF NOT EXISTS GEOPULSE_WH
WITH
    WAREHOUSE_SIZE = 'X-SMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

-- 2. Create database and schemas
CREATE DATABASE IF NOT EXISTS GEOPULSE_DB;

CREATE SCHEMA IF NOT EXISTS GEOPULSE_DB.RAW;
CREATE SCHEMA IF NOT EXISTS GEOPULSE_DB.STAGING;
CREATE SCHEMA IF NOT EXISTS GEOPULSE_DB.ANALYTICS;

-- 3. Create raw GPS table
CREATE TABLE IF NOT EXISTS GEOPULSE_DB.RAW.GPS_PINGS (
    DEVICE_ID VARCHAR(50),
    LATITUDE FLOAT,
    LONGITUDE FLOAT,
    PING_TIMESTAMP TIMESTAMP_NTZ,
    LOCATION GEOGRAPHY
);

-- 4. Create realistic mobility table
CREATE TABLE IF NOT EXISTS GEOPULSE_DB.RAW.REALISTIC_URBAN_MOBILITY (
    DEVICE_ID VARCHAR(50),
    LATITUDE FLOAT,
    LONGITUDE FLOAT,
    PING_TIMESTAMP TIMESTAMP_NTZ,
    PERIOD VARCHAR(20),
    ACTIVITY_ZONE VARCHAR(50),
    LOCATION GEOGRAPHY
);

-- 5. Create store locations table
CREATE TABLE IF NOT EXISTS GEOPULSE_DB.RAW.STORE_LOCATIONS (
    STORE_ID VARCHAR(50),
    STORE_NAME VARCHAR(100),
    LATITUDE FLOAT,
    LONGITUDE FLOAT,
    CATEGORY VARCHAR(50),
    STORE_SIZE_SQFT FLOAT,
    LOCATION GEOGRAPHY
);

-- 6. Create competitor locations table
CREATE TABLE IF NOT EXISTS GEOPULSE_DB.RAW.COMPETITOR_LOCATIONS (
    COMPETITOR_ID VARCHAR(50),
    COMPETITOR_NAME VARCHAR(100),
    LATITUDE FLOAT,
    LONGITUDE FLOAT,
    CATEGORY VARCHAR(50),
    COMPETITOR_SIZE_SQFT FLOAT,
    LOCATION GEOGRAPHY
);

-- 7. Create store catchments table
CREATE TABLE IF NOT EXISTS GEOPULSE_DB.RAW.STORE_CATCHMENTS (
    CATCHMENT_ID VARCHAR(50),
    STORE_ID VARCHAR(50),
    LATITUDE FLOAT,
    LONGITUDE FLOAT,
    CATCHMENT_RADIUS_M FLOAT,
    CATCHMENT_TYPE VARCHAR(50),
    LOCATION GEOGRAPHY
);

-- 8. Create commercial zones table
CREATE TABLE IF NOT EXISTS GEOPULSE_DB.RAW.COMMERCIAL_ZONES (
    ZONE_ID VARCHAR(50),
    ZONE_NAME VARCHAR(100),
    ZONE_TYPE VARCHAR(50),
    LATITUDE FLOAT,
    LONGITUDE FLOAT,
    LOCATION GEOGRAPHY
);

-- 9. CSV file format
CREATE OR REPLACE FILE FORMAT GEOPULSE_DB.RAW.GEOPULSE_CSV_FORMAT
    TYPE = CSV
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    NULL_IF = ('NULL', 'null', '');

-- 10. Internal stage
CREATE OR REPLACE STAGE GEOPULSE_DB.RAW.GEOPULSE_STAGE
    FILE_FORMAT = GEOPULSE_DB.RAW.GEOPULSE_CSV_FORMAT;

-- 11. Load realistic urban mobility data
COPY INTO GEOPULSE_DB.RAW.REALISTIC_URBAN_MOBILITY
(
    DEVICE_ID, LATITUDE, LONGITUDE, PING_TIMESTAMP,
    PERIOD, ACTIVITY_ZONE, LOCATION
)
FROM (
    SELECT
        $1::VARCHAR,
        $2::FLOAT,
        $3::FLOAT,
        $4::TIMESTAMP_NTZ,
        $5::VARCHAR,
        $6::VARCHAR,
        ST_MAKEPOINT($3::FLOAT, $2::FLOAT)
    FROM @GEOPULSE_DB.RAW.GEOPULSE_STAGE/realistic_urban_mobility.csv
)
FILE_FORMAT = (
    FORMAT_NAME = 'GEOPULSE_DB.RAW.GEOPULSE_CSV_FORMAT'
);

-- 12. Load original synthetic GPS data
COPY INTO GEOPULSE_DB.RAW.GPS_PINGS
(
    DEVICE_ID, LATITUDE, LONGITUDE, PING_TIMESTAMP, LOCATION
)
FROM (
    SELECT
        $1::VARCHAR,
        $2::FLOAT,
        $3::FLOAT,
        $4::TIMESTAMP_NTZ,
        ST_MAKEPOINT($3::FLOAT, $2::FLOAT)
    FROM @GEOPULSE_DB.RAW.GEOPULSE_STAGE/synthetic_gps_data.csv
)
FILE_FORMAT = (
    FORMAT_NAME = 'GEOPULSE_DB.RAW.GEOPULSE_CSV_FORMAT'
);

-- 13. Validate original GPS data
SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(LOCATION) AS GEOGRAPHY_ROWS,
    MIN(PING_TIMESTAMP) AS FIRST_PING,
    MAX(PING_TIMESTAMP) AS LAST_PING
FROM GEOPULSE_DB.RAW.GPS_PINGS;

-- 14. Validate realistic mobility data
SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(LOCATION) AS GEOGRAPHY_ROWS,
    MIN(PING_TIMESTAMP) AS FIRST_PING,
    MAX(PING_TIMESTAMP) AS LAST_PING
FROM GEOPULSE_DB.RAW.REALISTIC_URBAN_MOBILITY;

-- 15. Inspect geography values
SELECT
    DEVICE_ID,
    LATITUDE,
    LONGITUDE,
    ST_ASWKT(LOCATION) AS LOCATION_WKT
FROM GEOPULSE_DB.RAW.REALISTIC_URBAN_MOBILITY
LIMIT 5;
